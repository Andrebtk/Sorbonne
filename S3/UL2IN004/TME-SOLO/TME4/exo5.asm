.data
	tab: .word 4, 		# 0x10010000
		23, 		# 0x10010004 +4
		12, 		# 0x10010008 +8
		3, 		# 0x1001000c +12
		8, 		# 0x10010010 +16
		1		# 0x10010014 +20
	
	   .align 2
	s: .space 4		# 0x10010018 +24
	
	   .align 2
	p: .space 4		# 0x1001001c +28
	
.text
	lui $16, 0x1001		# $16 <- @data

	
	#s = tab[3];
	lw $9, 12($16)		# $9 <- tab[3]
	sw $9, 24($16)		# $9 -> s
	
	#p = tab[4];
	lw $11, 16($16)		# $11 <- tab[4]
	sw $11, 28($16)		# $11 -> p
	
	lw $17, 24($16)		# $17 <- s
	lw $18, 28($16)		# $18 <- p
	
	#tab[0] = s + 1;
	addiu $13, $17, 1	# $13 <- s+1
	sw $13, 0($16)		# $13 -> tab[0]
	
	#tab[1] = s + p;
	addu $14, $17, $18	# $14 <- s + p
	sw $14, 4($16)		# $14 -> tab[1]
	
	#tab[2] = tab[5];
	lw $12, 20($16)		# $12 <- tab[5]
	sw $12, 8($16)		# $12 -> tab[2]
	
			
	# Exit
	ori $2, $0, 10
	syscall